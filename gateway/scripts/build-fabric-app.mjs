import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const bundle = await build({
  entryPoints: [fileURLToPath(new URL("app/app.js", root))],
  bundle: true, write: false, minify: true, format: "esm", target: "es2022",
  outfile: "app.js", legalComments: "inline",
});
const script = bundle.outputFiles.find((file) => file.path.endsWith(".js")).text;
const sdkCss = bundle.outputFiles.find((file) => file.path.endsWith(".css"))?.text ?? "";
const css = await readFile(new URL("app/styles.css", root), "utf8");
const template = await readFile(new URL("app/index.html", root), "utf8");
const packages = ["@modelcontextprotocol/ext-apps", "@modelcontextprotocol/sdk", "@openai/mcp-extensions", "zod", "zod-to-json-schema"];
const notices = await Promise.all(packages.map(async (name) => {
  const packageRoot = new URL(`node_modules/${name}/`, root);
  const info = JSON.parse(await readFile(new URL("package.json", packageRoot), "utf8"));
  const license = await readFile(new URL("LICENSE", packageRoot), "utf8");
  return `${name} ${info.version}\n${license}`;
}));
const html = template.replace("/* APP_STYLES */", () => `${sdkCss}\n${css}`)
  .replace("/* APP_SCRIPT */", () => script.replaceAll("</script", "<\\/script"))
  .replace("</body>", () => `<script type="text/plain" id="third-party-notices">${notices.join("\n\n").replaceAll("</script", "<\\/script")}</script>\n</body>`);
if (Buffer.byteLength(html) > 2 * 1024 * 1024) throw new Error("Fabric App exceeds the 2 MiB resource budget");
const generated = `// Generated by npm run build:app. Do not edit.\nexport default ${JSON.stringify(html)};\n`;
const output = new URL("src/fabric-app/generated.js", root);
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== generated) {
    throw new Error("Fabric App bundle is stale; run npm run build:app");
  }
} else {
  await writeFile(output, generated);
}
console.log(`Fabric App ${process.argv.includes("--check") ? "verified" : "built"}: ${Buffer.byteLength(html)} bytes`);
